<?php

namespace App\Console\Commands;

use App\Support\Localization\Locales;
use App\Support\Localization\TranslationFiles;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Config;
use Illuminate\Support\Facades\File;

class ExportFrontendTranslations extends Command
{
    protected $signature = 'localization:export {--path= : Output directory for the generated files}';

    protected $description = 'Export the React dictionaries and their TypeScript keys';

    public function handle(TranslationFiles $files): int
    {
        $option = $this->option('path');
        $path = is_string($option) ? $option : resource_path('js/i18n/generated');
        $locales = Locales::all();

        $outputs = $imports = $modules = $keys = [];

        foreach (array_keys($locales) as $code) {
            $dictionary = $files->frontend($code);
            $keys += $dictionary;
            $file = 'php_'.$code.'.json';
            $binding = 'dictionary'.count($imports);
            $outputs[$file] = $this->json((object) $dictionary)."\n";
            $imports[] = 'import '.$binding.' from '.$this->json('./'.$file).';';
            $modules[] = '    '.$this->json($code).': '.$binding.',';
        }

        ksort($keys, SORT_STRING);
        $translationKeys = implode("\n", array_map(fn (string $key): string => '    | '.$this->json($key), array_keys($keys)));
        $definitions = $this->json((object) $locales);
        $default = $this->json(Locales::default());
        $fallback = $this->json(Config::string('localization.fallback'));

        $outputs['types.ts'] = <<<TS
            // Generated by php artisan localization:export.
            export type LocaleDefinition = {
                code: string;
                laravelLocale: string;
                htmlLang: string;
                label: string;
                direction: 'ltr' | 'rtl';
            };

            export const localeDefinitions = {$definitions} as const satisfies Record<string, LocaleDefinition>;
            export type LocaleCode = keyof typeof localeDefinitions;
            export const defaultLocale = {$default} satisfies LocaleCode;
            export const fallbackLocale = {$fallback} satisfies LocaleCode;

            export type TranslationKey =
            {$translationKeys};
            TS."\n";
        $outputs['files.ts'] = "// Generated by php artisan localization:export.\n"
            .implode("\n", $imports)."\n\nexport const dictionaries = {\n"
            .implode("\n", $modules)."\n};\n";

        File::ensureDirectoryExists($path);
        foreach ($outputs as $name => $content) {
            $file = $path.'/'.$name;

            if (! File::exists($file) || File::get($file) !== $content) {
                File::replace($file, $content);
            }
        }

        $this->info('Frontend translations exported.');

        return self::SUCCESS;
    }

    private function json(mixed $value): string
    {
        return json_encode($value, JSON_THROW_ON_ERROR | JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    }
}
